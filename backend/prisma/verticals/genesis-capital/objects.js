'use strict';

/**
 * Genesis Capital — modules, objects, fields, forms and pipelines.
 *
 * Every business rule in here is Builder metadata the admin can edit:
 *   - computed values are `formula` fields (PRD pricing, EMI, eligibility,
 *     KYC risk score, suitability score) over the safe formula language;
 *   - hard rules are `expression` validations or stage gates
 *     (`stage.config.required_fields` / `entry_rule`);
 *   - relationships are `lookup` fields, which also give every Party its
 *     related lists (the Client 360);
 *   - legal-entity scope is `config.business_unit_field`, information
 *     barriers are `config.barrier_zone` / `barrier_zone_field`.
 */

